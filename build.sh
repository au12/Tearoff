#!/bin/bash
# Builds build/Tearoff.app as a universal app (Apple Silicon + Intel). Needs Xcode or the Command Line Tools.
# ARCHS="arm64" ./build.sh builds for one architecture only (faster).
#   Contents/MacOS/Tearoff            the app
#   Contents/Helpers/tearoff          command-line tool
#   Contents/Helpers/tearoff-filter   CUPS filter (copied to /Library/Printers/Tearoff by the driver installer)
set -euo pipefail
cd "$(dirname "$0")"

ARCHS="${ARCHS:-${ARCH:-arm64 x86_64}}"
ARCH_FLAGS=()
for a in $ARCHS; do ARCH_FLAGS+=(--arch "$a"); done
APP="build/Tearoff.app"

if ! xcrun --find swift >/dev/null 2>&1; then
  echo "Swift not found. Install the Command Line Tools with:  xcode-select --install" >&2
  exit 1
fi

# CI passes VERSION/BUILD/COMMIT; local builds keep the defaults in BuildInfo.swift.
if [[ -n "${VERSION:-}" ]]; then
  BUILD="${BUILD:-0}"
  COMMIT="${COMMIT:-$(git rev-parse --short HEAD 2>/dev/null || echo local)}"
  cat > Sources/TearoffKit/BuildInfo.swift <<EOF2
// Generated by build.sh
public enum BuildInfo {
    public static let version = "$VERSION"
    public static let build = "$BUILD"
    public static let commit = "$COMMIT"
}
EOF2
fi

echo "→ Compiling ($ARCHS)…"
swift build -c release "${ARCH_FLAGS[@]}"
BIN="$(swift build -c release "${ARCH_FLAGS[@]}" --show-bin-path)"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Helpers" "$APP/Contents/Resources"
cp "$BIN/TearoffApp" "$APP/Contents/MacOS/Tearoff"
cp "$BIN/tearoff" "$APP/Contents/Helpers/tearoff"
cp "$BIN/tearoff-filter" "$APP/Contents/Helpers/tearoff-filter"
cp Resources/Info.plist "$APP/Contents/Info.plist"
if [[ -n "${VERSION:-}" ]]; then
  /usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
  /usr/libexec/PlistBuddy -c "Set :CFBundleVersion $BUILD" "$APP/Contents/Info.plist"
fi
# synthetic label PDFs for Diagnostics › Run Benchmark and `tearoff bench`
mkdir -p "$APP/Contents/Resources/Benchmark"
cp tests/fixtures/*.pdf "$APP/Contents/Resources/Benchmark/"

echo "→ Building icon…"
ICONSET="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$ICONSET"
for s in 16 32 128 256 512; do
  sips -z $s $s Resources/AppIcon.png --out "$ICONSET/icon_${s}x${s}.png" >/dev/null
  sips -z $((s*2)) $((s*2)) Resources/AppIcon.png --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/AppIcon.icns"

echo "→ Signing (ad-hoc)…"
codesign --force --sign - --identifier com.au12.tearoff.cli "$APP/Contents/Helpers/tearoff"
codesign --force --sign - --identifier com.au12.tearoff.filter "$APP/Contents/Helpers/tearoff-filter"
codesign --force --sign - --identifier com.au12.tearoff "$APP"

echo "✓ Built $APP"
